"use strict";
const assert = require("node:assert/strict");
const shared = require("../shared-conversation-composer.js");
assert.equal(shared.VERSION, "shared-composer-v1");
const guard = shared.createCompositionGuard();
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter" }, guard), true);
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter", shiftKey: true }, guard), false);
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter", ctrlKey: true }, guard), false);
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter", altKey: true }, guard), false);
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter", isComposing: true }, guard), false);
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter", keyCode: 229 }, guard), false);
guard.start();
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter" }, guard), false);
guard.update();
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter" }, guard), false);
guard.end();
assert.equal(shared.shouldSubmitOnEnter({ key: "Enter" }, guard), true);
const input = { scrollHeight: 220, style: {} };
assert.equal(shared.resizeTextarea(input, { minHeight: 50, maxHeight: 180 }), 180);
assert.equal(input.style.overflowY, "auto");
input.scrollHeight = 36;
assert.equal(shared.resizeTextarea(input, { minHeight: 50, maxHeight: 180 }), 50);
assert.equal(input.style.overflowY, "hidden");
