const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync(process.argv[2], "utf8");

class Element {
  constructor(tag = "div") { this.tagName = tag.toUpperCase(); this.children = []; this.dataset = {}; this.listeners = {}; this.attrs = {}; this.text = ""; this.disabled = false; this.hidden = false; }
  set textContent(value) { this.text = String(value); this.children = []; }
  get textContent() { return this.text + this.children.map((child) => child.textContent).join(" "); }
  set value(value) { this._value = String(value); }
  get value() { return this._value === undefined ? (this.tagName === "SELECT" ? this.children[0]?.value || "" : "") : this._value; }
  append(...children) { this.children.push(...children); }
  replaceChildren(...children) { this.children = children; this.text = ""; if (this.tagName === "SELECT") delete this._value; }
  setAttribute(key, value) { this.attrs[key] = String(value); }
  addEventListener(name, callback) { (this.listeners[name] ||= []).push(callback); }
  click() { if (!this.disabled) for (const callback of this.listeners.click || []) callback({ target: this }); }
  all() { return [this, ...this.children.flatMap((child) => child.all())]; }
}

const LINK = { mesh_node_id: "node/test/pc-one", label: "작업 PC", state: "active" };
const TOKEN = { id: "fake-id", name: "내 개발 도구", device_id: LINK.mesh_node_id, created_at: "2026-11-01T00:00:00Z", last_used_at: null, revoked_at: null };
// Deliberately not a usable credential; never generated by a production issuer.
const TOKEN_PLACEHOLDER = "TEST_ONLY_INVALID_CREDENTIAL";
const APPROVAL = { id: "approval-one", token_id: TOKEN.id, token_name: TOKEN.name, device_id: LINK.mesh_node_id,
  tool_name: "pc_write_file", arguments: { path: "C:/업무/초안.txt", content: "첫 줄\n<img src=x onerror=alert(1)>" },
  request_digest: "test-request-digest", created_at: TOKEN.created_at, expires_at: "2026-11-01T01:00:00Z", status: "pending" };
const clone = (value) => JSON.parse(JSON.stringify(value));
const settle = async () => { for (let i = 0; i < 8; ++i) await new Promise((resolve) => setImmediate(resolve)); };

function setup({ tokens = [], approvals = [], links = [LINK], status = 200 } = {}) {
  const ids = {};
  for (const name of ["Status", "Endpoint", "Name", "Issue", "Refresh", "List", "Approvals", "Issued", "Token", "Copy", "Hide", "Editor"]) ids["mcpGateway" + name] = new Element(["Name", "Endpoint", "Token"].includes(name) ? "input" : "div");
  ids.mcpGatewayDevice = new Element("select");
  ids.mcpGatewaySettings = new Element("section");
  ids.settingsDialog = new Element("dialog"); ids.settingsDialog.open = false;
  const events = {}, observers = [], calls = [], clipboard = [];
  const server = { tokens: clone(tokens), approvals: clone(approvals), links: clone(links), status, mutationStatus: 200, pending: null, pendingIssue: null, clipboardFails: false };
  let locale = "ko";
  const response = (status, body) => ({ status, json: async () => clone(body) });
  const window = {
    document: { readyState: "complete", getElementById: (id) => ids[id], createElement: (tag) => new Element(tag) },
    location: { origin: "https://chat.example.invalid" },
    navigator: { clipboard: { writeText: async (value) => { if (server.clipboardFails) throw new Error("blocked"); clipboard.push(value); } } },
    __padiemLocale: { text: (key) => locale + ":" + key },
    addEventListener: (name, callback) => { (events[name] ||= []).push(callback); },
    MutationObserver: class { constructor(callback) { observers.push(callback); } observe() {} },
    fetch: async (url, options) => {
      calls.push({ url, ...options });
      if (url === "/api/pc/pairings") return response(200, { ok: true, links: server.links });
      if (options.method === "GET") {
        if (server.pending) return server.pending;
        const key = url.endsWith("tokens") ? "tokens" : "approvals";
        return response(server.status, { ok: server.status === 200, [key]: server[key] });
      }
      if (server.mutationStatus !== 200) return response(server.mutationStatus, { ok: false });
      if (url === "/api/account/mcp/tokens" && options.method === "POST") {
        if (server.pendingIssue) return server.pendingIssue;
        const body = JSON.parse(options.body), token = { ...TOKEN, ...body };
        server.tokens.unshift(token);
        return response(201, { ok: true, ...token, token: TOKEN_PLACEHOLDER });
      }
      if (options.method === "DELETE") {
        server.tokens = server.tokens.filter((token) => !url.endsWith("/" + token.id));
        return response(200, { ok: true });
      }
      const payload = JSON.parse(options.body), approval = server.approvals.find((item) => url.endsWith("/" + item.id));
      if (!approval || payload.request_digest !== approval.request_digest) return response(409, { ok: false });
      approval.status = payload.decision === "approve" ? "approved" : "denied";
      return response(200, { ok: true, approval });
    },
  };
  vm.runInNewContext(source, { window });
  return {
    ids, calls, server, clipboard,
    async open() { ids.settingsDialog.open = true; observers.forEach((callback) => callback()); await settle(); },
    async close() { ids.settingsDialog.open = false; observers.forEach((callback) => callback()); await settle(); },
    async event(name) { for (const callback of events[name] || []) callback(); await settle(); },
    language(value) { locale = value; },
    tokenText() { return ids.mcpGatewayList.textContent; },
    approvalText() { return ids.mcpGatewayApprovals.textContent; },
    button(key) { return [...ids.mcpGatewayList.all(), ...ids.mcpGatewayApprovals.all()].find((node) => node.tagName === "BUTTON" && node.textContent.endsWith(key)); },
    async issue() { ids.mcpGatewayName.value = TOKEN.name; ids.mcpGatewayIssue.click(); await settle(); },
  };
}

async function main() {
  const checks = [];
  async function check(name, callback) { await callback(); checks.push(name); }
  await check("initial settings only read account data and never persist credentials", async () => {
    const app = setup(); assert.equal(app.calls.length, 0); await app.open();
    assert.equal(app.calls.length, 3);
    assert.ok(app.calls.every((call) => call.method === "GET" && call.credentials === "same-origin" && call.cache === "no-store"));
    assert.equal(app.ids.mcpGatewayEndpoint.value, "https://chat.example.invalid/api/mcp");
    assert.ok(!/localStorage|sessionStorage|innerHTML|console\./.test(source));
    assert.match(app.tokenText(), /mcp-settings-empty/);
  });
  await check("issue is scoped to the chosen PC and displayed once outside metadata", async () => {
    const app = setup(); await app.open(); await app.issue();
    const call = app.calls.find((row) => row.method === "POST");
    assert.deepEqual(JSON.parse(call.body), { name: TOKEN.name, device_id: LINK.mesh_node_id });
    assert.equal(app.ids.mcpGatewayToken.value, TOKEN_PLACEHOLDER);
    assert.equal(app.ids.mcpGatewayIssued.hidden, false);
    assert.ok(!app.tokenText().includes(TOKEN_PLACEHOLDER));
    assert.equal(app.ids.mcpGatewayIssue.disabled, true);
    app.ids.mcpGatewayCopy.click(); await settle();
    assert.deepEqual(app.clipboard, [TOKEN_PLACEHOLDER]);
    app.ids.mcpGatewayHide.click();
    assert.equal(app.ids.mcpGatewayToken.value, "");
    assert.equal(app.ids.mcpGatewayIssued.hidden, true);
    assert.equal(app.ids.mcpGatewayIssue.disabled, false);
  });
  await check("closing and reopening clears issued token and sensitive request preview", async () => {
    const app = setup({ approvals: [APPROVAL] }); await app.open(); await app.issue();
    await app.close();
    assert.equal(app.ids.mcpGatewayToken.value, "");
    assert.ok(!app.approvalText().includes(APPROVAL.arguments.content));
    await app.open();
    assert.equal(app.ids.mcpGatewayToken.value, "");
    assert.equal(app.ids.mcpGatewayIssued.hidden, true);
    assert.match(app.tokenText(), /내 개발 도구/);
  });
  await check("exact write content is visible as inert text before approval", async () => {
    const app = setup({ approvals: [APPROVAL] }); await app.open();
    for (const value of [TOKEN.name, LINK.label, APPROVAL.tool_name, APPROVAL.arguments.path, APPROVAL.arguments.content]) assert.ok(app.approvalText().includes(value));
    assert.ok(!app.ids.mcpGatewayApprovals.all().some((node) => node.tagName === "IMG"));
    const pre = app.ids.mcpGatewayApprovals.all().find((node) => node.tagName === "PRE");
    assert.deepEqual(JSON.parse(pre.textContent), APPROVAL.arguments);
  });
  await check("move and deletion options remain completely visible", async () => {
    const move = { ...APPROVAL, arguments: { source_path: "C:/a.txt", destination_path: "C:/b.txt", overwrite: false } };
    const app = setup({ approvals: [move, { ...APPROVAL, id: "deletion", tool_name: "pc_delete_file", arguments: { path: "C:/old", recursive: true } }] });
    await app.open();
    for (const value of ["C:/a.txt", "C:/b.txt", "C:/old", '"overwrite": false', '"recursive": true', "mcp-settings-destination"]) assert.ok(app.approvalText().includes(value));
  });
  await check("approval sends the displayed digest and requires an external exact retry", async () => {
    const app = setup({ approvals: [APPROVAL] }); await app.open();
    app.button("mcp-settings-approve").click(); await settle();
    const call = app.calls.find((row) => row.method === "POST");
    assert.equal(call.url, "/api/account/mcp/approvals/approval-one");
    assert.deepEqual(JSON.parse(call.body), { decision: "approve", request_digest: APPROVAL.request_digest });
    assert.match(app.approvalText(), /mcp-settings-approved/);
    assert.equal(app.button("mcp-settings-approve"), undefined);
    assert.ok(!app.calls.some((row) => row.url === "/api/mcp"));
  });
  await check("denial records only the exact pending request decision", async () => {
    const app = setup({ approvals: [APPROVAL] }); await app.open();
    app.button("mcp-settings-deny").click(); await settle();
    assert.equal(app.server.approvals[0].status, "denied");
    assert.match(app.approvalText(), /mcp-settings-denied/);
    assert.equal(app.button("mcp-settings-approve"), undefined);
  });
  await check("revoking a connection clears token and its pending approvals", async () => {
    const app = setup({ approvals: [APPROVAL] }); await app.open(); await app.issue();
    app.button("mcp-settings-revoke").click(); await settle();
    assert.equal(app.ids.mcpGatewayToken.value, "");
    assert.equal(app.server.tokens.length, 0);
    assert.ok(!app.approvalText().includes(APPROVAL.arguments.path));
    assert.match(app.ids.mcpGatewayStatus.textContent, /mcp-settings-revoked/);
  });
  await check("uncertain mutation never reports success or permits another decision", async () => {
    const app = setup({ tokens: [TOKEN], approvals: [APPROVAL] }); await app.open(); app.server.mutationStatus = 503;
    app.button("mcp-settings-approve").click(); await settle();
    assert.equal(app.server.approvals[0].status, "pending");
    assert.equal(app.button("mcp-settings-approve").disabled, true);
    assert.equal(app.button("mcp-settings-revoke").disabled, true);
    assert.equal(app.ids.mcpGatewayRefresh.disabled, false);
    assert.match(app.ids.mcpGatewayStatus.textContent, /mcp-settings-save-error/);
  });
  await check("signed out account removes credentials and previous owner data", async () => {
    const app = setup({ approvals: [APPROVAL] }); await app.open(); await app.issue();
    app.server.status = 401; await app.event("padiem:auth-state");
    assert.equal(app.ids.mcpGatewayToken.value, "");
    assert.ok(!app.approvalText().includes(APPROVAL.arguments.path));
    assert.ok(!app.tokenText().includes(TOKEN.name));
    assert.equal(app.ids.mcpGatewayIssue.disabled, true);
  });
  await check("late token issue response after account change is discarded", async () => {
    const app = setup(); await app.open(); let resolve;
    app.server.pendingIssue = new Promise((done) => { resolve = done; });
    await app.issue(); app.server.status = 401; await app.event("padiem:auth-state");
    resolve({ status: 201, json: async () => ({ ok: true, ...TOKEN, token: TOKEN_PLACEHOLDER }) }); await settle();
    assert.equal(app.ids.mcpGatewayToken.value, "");
    assert.equal(app.ids.mcpGatewayIssued.hidden, true);
    assert.ok(!app.tokenText().includes(TOKEN.name));
  });
  await check("paused PC cannot receive a token while old tokens remain revocable", async () => {
    const app = setup({ tokens: [TOKEN], links: [{ ...LINK, state: "paused" }] }); await app.open();
    assert.equal(app.ids.mcpGatewayIssue.disabled, true);
    assert.equal(app.button("mcp-settings-revoke").disabled, false);
    assert.ok(app.tokenText().includes(LINK.label));
    app.language("en"); await app.event("padiem:localechange");
    assert.equal(app.button("mcp-settings-revoke").textContent, "en:mcp-settings-revoke");
  });
  await check("missing name does not issue a token", async () => {
    const app = setup(); await app.open(); app.ids.mcpGatewayIssue.click(); await settle();
    assert.ok(!app.calls.some((row) => row.method === "POST"));
    assert.match(app.ids.mcpGatewayStatus.textContent, /mcp-settings-required/);
  });
  await check("clipboard failure keeps only the visible token for manual copy", async () => {
    const app = setup(); await app.open(); await app.issue(); app.server.clipboardFails = true;
    app.ids.mcpGatewayCopy.click(); await settle();
    assert.equal(app.clipboard.length, 0);
    assert.equal(app.ids.mcpGatewayToken.value, TOKEN_PLACEHOLDER);
    assert.match(app.ids.mcpGatewayStatus.textContent, /mcp-settings-copy-error/);
    app.ids.mcpGatewayRefresh.click(); await settle();
    assert.equal(app.ids.mcpGatewayToken.value, "");
  });
  for (const name of checks) console.log("MCP_GATEWAY_CHECK " + name + " PASS");
  console.log("MCP_GATEWAY_SETTINGS=PASS");
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
