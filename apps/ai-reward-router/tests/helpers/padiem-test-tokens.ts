import { spawnSync } from 'node:child_process';

/**
 * Test-only session token minting for the B64 pipeline tests.
 *
 * The signed `padiem_session` tokens used in tests are generated at runtime,
 * never stored in the repository: signed HMAC blobs look like generic
 * high-entropy secrets to secret scanners (GitGuardian flagged the previous
 * hardcoded fixtures), and per the repository rules real-looking credentials
 * stay out of source regardless. The verification code under test is
 * unchanged.
 *
 * Two minting paths exist:
 * - `signTestSessionToken`: a TS port of the B62 `_signed_token` shape,
 *   used for the deterministic reject/accept matrix in every environment.
 * - `mintWithRealChatAuthority`: runs the REAL B62 authority
 *   (`apps/padiem-chat/app/auth.py`) through a python subprocess and returns
 *   its tokens — the actual cross-language proof. Returns null when python
 *   or the chat app is unavailable, so callers can skip that comparison.
 */

const B64URL_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';

export const SESSION_TOKEN_PURPOSE = 'padiem-chat/session/v1';

function b64urlEncode(bytes: Uint8Array): string {
  let output = '';
  let bits = 0;
  let accumulator = 0;
  for (const byte of bytes) {
    accumulator = (accumulator << 8) | byte;
    bits += 8;
    while (bits >= 6) {
      bits -= 6;
      output += B64URL_ALPHABET[(accumulator >> bits) & 0x3f];
    }
  }
  if (bits > 0) {
    output += B64URL_ALPHABET[(accumulator << (6 - bits)) & 0x3f];
  }
  return output;
}

function utf8Bytes(value: string): Uint8Array {
  return new TextEncoder().encode(value);
}

async function hmacSha256(keyBytes: Uint8Array, messageBytes: Uint8Array): Promise<Uint8Array> {
  const key = await crypto.subtle.importKey(
    'raw',
    keyBytes as BufferSource,
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign'],
  );
  const signature = await crypto.subtle.sign('HMAC', key, messageBytes as BufferSource);
  return new Uint8Array(signature);
}

export interface TestSessionPayload {
  v: number;
  uid: string;
  exp: number;
  sid?: string;
}

/** Mints one signed token with the B62 wire shape (`<b64url payload>.<b64url sig>`). */
export async function signTestSessionToken(
  payload: TestSessionPayload,
  secret: string,
  purpose: string = SESSION_TOKEN_PURPOSE,
): Promise<string> {
  const canonical = JSON.stringify(payload, Object.keys(payload).sort());
  const body = b64urlEncode(utf8Bytes(canonical));
  const key = await hmacSha256(utf8Bytes(secret), utf8Bytes(purpose));
  const signature = await hmacSha256(key, utf8Bytes(body));
  return `${body}.${b64urlEncode(signature)}`;
}

export interface FixtureTokenSet {
  validToken: string;
  validTokenWithSid: string;
  expiredToken: string;
  wrongPurposeToken: string;
  wrongSecretToken: string;
  badUidToken: string;
  longUidToken: string;
  emptyUidToken: string;
  badSidToken: string;
  wrongVersionToken: string;
  nonDictPayloadToken: string;
  tamperedBodyToken: string;
  tamperedSigToken: string;
}

/**
 * Mints the full reject/accept fixture set. Mirrors the set previously
 * generated by the real authority for the committed fixtures file; every
 * reject case is a signed token whose payload or purpose is out of contract.
 */
export async function mintFixtureTokenSet(
  secret: string,
  issuedAt: number,
  maxAgeSeconds: number,
  secondSecret = 'other-secret-aaaaaaaaaaaaaaaaaaaaaaaaaaaa',
): Promise<FixtureTokenSet> {
  const exp = issuedAt + maxAgeSeconds;
  const validToken = await signTestSessionToken({ v: 1, uid: 'usr_fixture_user_0001', exp }, secret);
  const validTokenWithSid = await signTestSessionToken(
    { v: 1, uid: 'usr_fixture_user_0002', exp, sid: 'sess_FixtureCanonical-0001' },
    secret,
  );
  const tamper = (token: string, at: number, replacement: string) =>
    token.slice(0, at) + replacement + token.slice(at + 1);

  return {
    validToken,
    validTokenWithSid,
    expiredToken: await signTestSessionToken({ v: 1, uid: 'usr_fixture_user_0001', exp: 1000000000 }, secret),
    wrongPurposeToken: await signTestSessionToken(
      { v: 1, uid: 'usr_fixture_user_0001', exp },
      secret,
      'padiem-chat/oauth-state/v1',
    ),
    wrongSecretToken: await signTestSessionToken({ v: 1, uid: 'usr_fixture_user_0001', exp }, secondSecret),
    badUidToken: await signTestSessionToken({ v: 1, uid: 'attacker_123', exp }, secret),
    longUidToken: await signTestSessionToken({ v: 1, uid: `usr_${'a'.repeat(80)}`, exp }, secret),
    emptyUidToken: await signTestSessionToken({ v: 1, uid: '', exp }, secret),
    badSidToken: await signTestSessionToken(
      { v: 1, uid: 'usr_fixture_user_0001', exp, sid: '../../etc-passwd' },
      secret,
    ),
    wrongVersionToken: await signTestSessionToken({ v: 2, uid: 'usr_fixture_user_0001', exp }, secret),
    nonDictPayloadToken: await signTestSessionToken({ v: 1, uid: 'usr_fixture_user_0001', exp }, secret)
      // replace the payload body wholesale with the encoding of a JSON array,
      // keeping the (now invalid) signature
      .then((token) => {
        const arrayBody = b64urlEncode(utf8Bytes('["not","a","dict"]'));
        const signaturePart = token.split('.')[1] ?? '';
        return `${arrayBody}.${signaturePart}`;
      }),
    tamperedBodyToken: tamper(validToken, 0, validToken.startsWith('A') ? 'B' : 'A'),
    tamperedSigToken: (() => {
      const [bodyPart = '', signaturePart = ''] = validToken.split('.');
      return `${bodyPart}.${tamper(signaturePart, 0, signaturePart.startsWith('A') ? 'B' : 'A')}`;
    })(),
  };
}

/**
 * Mints a token with the REAL B62 session authority through python.
 * Returns null when python or the chat app is unavailable, so the
 * cross-language comparison can be skipped in that environment.
 */
export async function mintWithRealChatAuthority(
  secret: string,
  uid: string,
  issuedAt: number,
  maxAgeSeconds: number,
  canonicalSessionId?: string,
): Promise<string | null> {
  const appDirUrl = new URL('../../../../../apps/padiem-chat/app/', import.meta.url);
  const appDir = decodeURIComponent(appDirUrl.pathname).replace(/^\/([A-Za-z]:)/, '$1').replace(/\/$/, '');
  const script = `
import importlib.util, sys, types
APP = r'${appDir}'
pkg = types.ModuleType('padiem_chat_app'); pkg.__path__ = [APP]; sys.modules['padiem_chat_app'] = pkg
sys.modules['padiem_chat_app.httpx_compat'] = types.ModuleType('padiem_chat_app.httpx_compat')
cfg = types.ModuleType('padiem_chat_app.config')
class Settings:
    def __init__(self, session_secret=None, session_max_age_seconds=604800):
        self.session_secret = session_secret
        self.session_max_age_seconds = session_max_age_seconds
cfg.Settings = Settings
sys.modules['padiem_chat_app.config'] = cfg
spec = importlib.util.spec_from_file_location('padiem_chat_app.auth', APP + '/auth.py')
auth = importlib.util.module_from_spec(spec)
sys.modules['padiem_chat_app.auth'] = auth
spec.loader.exec_module(auth)
s = Settings(session_secret=${JSON.stringify(secret)}, session_max_age_seconds=${maxAgeSeconds})
token = auth.create_session_token(s, ${JSON.stringify(uid)}, now=${issuedAt}${canonicalSessionId ? `, canonical_session_id=${JSON.stringify(canonicalSessionId)}` : ''})
sys.stdout.write(token)
`;
  try {
    const result = spawnSync('python', ['-'], { input: script, timeout: 30000, encoding: 'utf8' });
    if (result.error || result.status !== 0) return null;
    const token = (result.stdout ?? '').trim();
    return token.includes('.') ? token : null;
  } catch {
    return null;
  }
}
