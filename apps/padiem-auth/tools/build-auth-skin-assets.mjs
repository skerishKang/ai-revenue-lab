#!/usr/bin/env node
// Regenerates apps/padiem-auth/skin-assets.mjs from static/auth-skin.
//
// The auth Worker deploys as one module with no static-asset binding, so the
// login screen carries its fonts and images as base64 constants and serves them
// from /assets/auth-skin/* on the same origin (zero external requests). The raw
// files stay under static/auth-skin for provenance and licence review.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const source = join(app, 'static', 'auth-skin');

const ASSETS = [
  ['card-1.webp', 'assets/card-1.webp', 'image/webp'],
  ['card-2.webp', 'assets/card-2.webp', 'image/webp'],
  ['card-3.webp', 'assets/card-3.webp', 'image/webp'],
  ['card-4.webp', 'assets/card-4.webp', 'image/webp'],
  ['googleg-standard-color.svg', 'assets/googleg-standard-color.svg', 'image/svg+xml'],
  ['fonts/GowunBatang-Bold.latin.woff2', 'assets/fonts/GowunBatang-Bold.latin.woff2', 'font/woff2'],
  ['fonts/Roboto-Medium.latin.woff2', 'assets/fonts/Roboto-Medium.latin.woff2', 'font/woff2'],
  ['fonts/Roboto-Medium.latin-ext.woff2', 'assets/fonts/Roboto-Medium.latin-ext.woff2', 'font/woff2'],
];

const wrap = (text, width) => text.match(new RegExp(`.{1,${width}}`, 'g')) || [];

let out = `// Generated by tools/build-auth-skin-assets.mjs - do not edit by hand.
// Source files: static/auth-skin, copied byte-for-byte from
// skerishKang/lovetree-4.0 docs/design/auth-skin (PR #208/commit e9e82e6;
// cards refreshed by #347/commit 3346374).
// The login screen serves these bytes from /assets/auth-skin/* so the page
// makes no external request.
export const AUTH_SKIN_ASSETS = Object.freeze({
`;
for (const [name, file, type] of ASSETS) {
  const base64 = readFileSync(join(source, file)).toString('base64');
  const lines = wrap(base64, 88).map((line) => `    '${line}'`).join(' +\n');
  out += `  '${name}': Object.freeze({\n    type: '${type}',\n    base64:\n${lines},\n  }),\n`;
}
out += '});\n';
writeFileSync(join(app, 'skin-assets.mjs'), out);
console.log(`wrote skin-assets.mjs (${ASSETS.length} assets)`);
