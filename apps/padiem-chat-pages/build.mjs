// Assembles the Pages upload directory.
//
//   dist/                apps/padiem-chat/static (the same files the Worker's
//                        ASSETS binding serves) — Pages serves these directly
//   dist/_redirects      pretty-URL rewrites the Pages asset layer must apply
//                        (see buildRedirects)
//   dist/_worker/        the reviewed apps/padiem-chat-front modules, copied
//                        verbatim so there is one proxy implementation
//   dist/_worker.js      the advanced-mode entry that re-exports that module
//
// Nothing generated here is committed: `dist/` is ignored, and every deploy
// rebuilds it from the repository sources.
import { cp, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { stampStaticTree } from "../../deploy/chat-release/stamp_index_html.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..");
const staticDir = path.join(repoRoot, "apps", "padiem-chat", "static");
const frontDir = path.join(repoRoot, "apps", "padiem-chat-front");
const distDir = path.join(here, "dist");

// worker.mjs imports these two siblings; they must sit next to it in dist.
const FRONT_MODULES = ["worker.mjs", "edge-proof.mjs", "error-copy.mjs"];

const entry = `// Generated by apps/padiem-chat-pages/build.mjs — do not edit.
// Advanced mode: this Pages project runs the exact padiem-chat-front proxy.
export { default } from "./_worker/worker.mjs";
`;

// The release script pins the version to the released commit (env override).
// A standalone build falls back to the current HEAD so a dev-run dist still
// serves versioned asset URLs.
async function assetVersion() {
  const fromEnv = (process.env.PADIEM_ASSET_VERSION || "").trim();
  if (fromEnv) return fromEnv;
  const { execFile } = await import("node:child_process");
  const { promisify } = await import("node:util");
  try {
    const { stdout } = await promisify(execFile)("git", ["rev-parse", "--short=8", "HEAD"], { cwd: repoRoot });
    return stdout.trim();
  } catch {
    return "dev";
  }
}

// chat.padiem.net serves the root-level *.html pages extension-less through
// the Worker's [assets] html_handling (privacy -> privacy.html). The Pages
// asset layer does not apply that resolution when a _worker.js is deployed:
// without these rewrites /privacy and /terms fall through to the proxy and
// come back 404 from COM2, which has no such route (#7130-era pages mirror).
async function buildRedirects(outDir) {
  const entries = await readdir(staticDir, { withFileTypes: true });
  const lines = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".html") && entry.name !== "index.html")
    .map((entry) => `/${entry.name.replace(/\.html$/, "")} /${entry.name} 200`);
  await writeFile(path.join(outDir, "_redirects"), lines.join("\n") + "\n", "utf8");
  return lines;
}

export async function buildDist({ outDir = distDir } = {}) {
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  await cp(staticDir, outDir, { recursive: true });
  // Same stamp as the Worker's deploy copy: every HTML entry gets ?v=<version>
  // on its local script/link references and every JS/CSS asset literal that
  // loads another static file carries the same version. The repository files
  // are untouched — only dist/ is stamped.
  const version = await assetVersion();
  const stamped = await stampStaticTree(outDir, version);
  await buildRedirects(outDir);
  const modulesDir = path.join(outDir, "_worker");
  await mkdir(modulesDir, { recursive: true });
  for (const name of FRONT_MODULES) {
    await cp(path.join(frontDir, name), path.join(modulesDir, name));
  }
  await writeFile(path.join(outDir, "_worker.js"), entry, "utf8");
  console.log(`padiem-chat-pages: assets stamped ?v=${version} (html ${stamped.htmlRefs}, js/css ${stamped.assetRefs}, ${stamped.filesChanged} files)`);
  return outDir;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = await buildDist();
  console.log(`padiem-chat-pages: assembled ${path.relative(repoRoot, out)}`);
}
